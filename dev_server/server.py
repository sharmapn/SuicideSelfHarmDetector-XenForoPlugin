@app.route("/", methods=["GET"])
def index():
    return jsonify({
        "service": "SuicideSelfHarmDetector classifier API",
        "status": "running",
        "model": "Linear SVM",
        "model_kind": MODEL["kind"],
        "score_type": SCORE_TYPE,
    })


@app.route("/health", methods=["GET"])
def health():
    return jsonify({
        "ok": True,
        "model_loaded": True,
        "model": "Linear SVM",
        "model_kind": MODEL["kind"],
    })


@app.route("/api/classify", methods=["POST"])
@app.route("/", methods=["POST"])
def classify():
    if not check_api_key():
        return jsonify({
            "risk_level": "unknown",
            "recommended_action": "moderate",
            "highest_label": "",
            "highest_score": 0,
            "flagged_parts": [],
            "error": "Unauthorized request.",
        }), 401

    try:
        payload = request.get_json(silent=True)
        if not isinstance(payload, dict):
            return jsonify({
                "risk_level": "unknown",
                "recommended_action": "moderate",
                "highest_label": "",
                "highest_score": 0,
                "flagged_parts": [],
                "error": "Invalid JSON payload.",
            }), 400

        return jsonify(classify_payload(payload)), 200

    except ValueError as exc:
        return jsonify({
            "risk_level": "unknown",
            "recommended_action": "moderate",
            "highest_label": "",
            "highest_score": 0,
            "flagged_parts": [],
            "error": str(exc),
        }), 400
    except Exception as exc:
        traceback.print_exc()
        return jsonify({
            "risk_level": "unknown",
            "recommended_action": "moderate",
            "highest_label": "",
            "highest_score": 0,
            "flagged_parts": [],
            "error": str(exc),
        }), 500


if __name__ == "__main__":
    app.run(debug=False, host=HOST, port=PORT)
